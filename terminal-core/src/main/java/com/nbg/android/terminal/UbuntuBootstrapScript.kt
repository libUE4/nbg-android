nbg_android_export_proxy_aliases() {
  if [ -n "${'$'}{HTTP_PROXY:-}" ] && [ -z "${'$'}{http_proxy:-}" ]; then export http_proxy="${'$'}HTTP_PROXY"; fi
  if [ -n "${'$'}{http_proxy:-}" ] && [ -z "${'$'}{HTTP_PROXY:-}" ]; then export HTTP_PROXY="${'$'}http_proxy"; fi
  if [ -n "${'$'}{HTTPS_PROXY:-}" ] && [ -z "${'$'}{https_proxy:-}" ]; then export https_proxy="${'$'}HTTPS_PROXY"; fi
  if [ -n "${'$'}{https_proxy:-}" ] && [ -z "${'$'}{HTTPS_PROXY:-}" ]; then export HTTPS_PROXY="${'$'}https_proxy"; fi
  if [ -n "${'$'}{ALL_PROXY:-}" ] && [ -z "${'$'}{all_proxy:-}" ]; then export all_proxy="${'$'}ALL_PROXY"; fi
  if [ -n "${'$'}{all_proxy:-}" ] && [ -z "${'$'}{ALL_PROXY:-}" ]; then export ALL_PROXY="${'$'}all_proxy"; fi
  if [ -n "${'$'}{NO_PROXY:-}" ] && [ -z "${'$'}{no_proxy:-}" ]; then export no_proxy="${'$'}NO_PROXY"; fi
  if [ -n "${'$'}{no_proxy:-}" ] && [ -z "${'$'}{NO_PROXY:-}" ]; then export NO_PROXY="${'$'}no_proxy"; fi
  if [ -n "${'$'}{http_proxy:-}" ]; then
    export npm_config_proxy="${'$'}{npm_config_proxy:-${'$'}http_proxy}"
    export NPM_CONFIG_PROXY="${'$'}{NPM_CONFIG_PROXY:-${'$'}http_proxy}"
  fi
  if [ -n "${'$'}{https_proxy:-}" ]; then
    export npm_config_https_proxy="${'$'}{npm_config_https_proxy:-${'$'}https_proxy}"
    export NPM_CONFIG_HTTPS_PROXY="${'$'}{NPM_CONFIG_HTTPS_PROXY:-${'$'}https_proxy}"
  fi
}

nbg_android_prepare_random_devices() {
  case " ${'$'}{JAVA_TOOL_OPTIONS:-} " in
    *" -Djava.security.egd=file:/dev/./urandom "*) ;;
    *) export JAVA_TOOL_OPTIONS="-Djava.security.egd=file:/dev/./urandom${'$'}{JAVA_TOOL_OPTIONS:+ ${'$'}JAVA_TOOL_OPTIONS}" ;;
  esac
  case " ${'$'}{GRADLE_OPTS:-} " in
    *" -Djava.security.egd=file:/dev/./urandom "*) ;;
    *) export GRADLE_OPTS="-Djava.security.egd=file:/dev/./urandom${'$'}{GRADLE_OPTS:+ ${'$'}GRADLE_OPTS}" ;;
  esac
  if [ -c /dev/urandom ] && [ -c /dev/random ]; then
    return 0
  fi
  if [ -p /dev/urandom ] || [ -L /dev/urandom ]; then
    return 0
  fi
  [ ! -c /dev/urandom ] && [ ! -p /dev/urandom ] && [ ! -L /dev/urandom ] && rm -f /dev/urandom 2>/dev/null || true
  [ ! -c /dev/random ] && [ ! -p /dev/random ] && [ ! -L /dev/random ] && rm -f /dev/random 2>/dev/null || true
  if command -v python3 >/dev/null 2>&1 && command -v mkfifo >/dev/null 2>&1; then
    if mkfifo /dev/urandom 2>/dev/null; then
      ln -sf /dev/urandom /dev/random 2>/dev/null || true
      (
        while true; do
          python3 -c 'import os,sys
while True:
    sys.stdout.buffer.write(os.urandom(4096))
    sys.stdout.buffer.flush()
' > /dev/urandom 2>/dev/null
          sleep 0.2
        done
      ) >/dev/null 2>&1 &
      return 0
    fi
  fi
  if [ -c /dev/zero ]; then
    [ ! -e /dev/urandom ] && ln -s /dev/zero /dev/urandom 2>/dev/null || true
    [ ! -e /dev/random ] && ln -s /dev/zero /dev/random 2>/dev/null || true
  fi
}

nbg_android_detect_toolchains() {
  nbg_android_prepend_path /opt/hanakopro-server
  nbg_android_prepend_path /usr/local/node-v24/bin
  nbg_android_prepend_path /root/.local/bin
  if [ -d /opt/android-sdk ]; then
    export ANDROID_HOME="${'$'}{ANDROID_HOME:-/opt/android-sdk}"
    export ANDROID_SDK_ROOT="${'$'}{ANDROID_SDK_ROOT:-/opt/android-sdk}"
    nbg_android_prepend_path /opt/android-sdk/platform-tools
    nbg_android_prepend_path /opt/android-sdk/cmdline-tools/latest/bin
    for build_tools_dir in /opt/android-sdk/build-tools/*; do
      [ -d "${'$'}build_tools_dir" ] && nbg_android_prepend_path "${'$'}build_tools_dir"
    done
  fi
  for java_home in /usr/lib/jvm/java-21-openjdk-arm64 /usr/lib/jvm/java-17-openjdk-arm64 /opt/jdk-21 /opt/jdk-17; do
    if [ -x "${'$'}java_home/bin/java" ]; then
      export JAVA_HOME="${'$'}{JAVA_HOME:-${'$'}java_home}"
      nbg_android_prepend_path "${'$'}JAVA_HOME/bin"
      break
    fi
  done
  export PATH
}

nbg_android_fix_executables() {
  for sdk_tool in \
    /opt/android-sdk/cmdline-tools/latest/bin/sdkmanager \
    /opt/android-sdk/cmdline-tools/latest/bin/avdmanager \
    /opt/android-sdk/platform-tools/adb
  do
    [ -f "${'$'}sdk_tool" ] && chmod 755 "${'$'}sdk_tool" 2>/dev/null || true
  done
  for gradlew in /root/*/gradlew /root/*/*/gradlew /storage/emulated/0/NBG/*/gradlew /storage/emulated/0/NBG/*/*/gradlew; do
    [ -f "${'$'}gradlew" ] && chmod 755 "${'$'}gradlew" 2>/dev/null || true
  done
}

