        if [ -f "${'$'}build_wrapper" ] && "${'$'}BIN/busybox" cmp -s "${'$'}build_wrapper_tmp" "${'$'}build_wrapper"; then
          rm -f "${'$'}build_wrapper_tmp" 2>/dev/null || true
        else
          mv "${'$'}build_wrapper_tmp" "${'$'}build_wrapper" || return 1
          chmod 755 "${'$'}build_wrapper"
        fi
      }

      write_full_ubuntu_sources() {
        mkdir -p "${'$'}UBUNTU_ROOT/etc/apt" 2>/dev/null || true
        cat <<'EOF' > "${'$'}UBUNTU_ROOT/etc/apt/sources.list"
# From NBG Android default source profile
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports/ noble main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports/ noble-updates main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports/ noble-backports main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports/ noble-security main restricted universe multiverse
EOF
      }

      write_base_ubuntu_sources() {
        mkdir -p "${'$'}UBUNTU_ROOT/etc/apt" 2>/dev/null || true
        cat <<'EOF' > "${'$'}UBUNTU_ROOT/etc/apt/sources.list"
# From NBG Android base source profile used while installing default tools
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports/ noble main restricted universe multiverse
EOF
      }

      configure_package_sources() {
        write_android_proxy_profile || return 1
        write_android_runtime_profile || return 1
        write_full_ubuntu_sources
        mkdir -p "${'$'}UBUNTU_ROOT/root/.config/pip" "${'$'}UBUNTU_ROOT/root/.config/uv" 2>/dev/null || true
        echo '[global]' > "${'$'}UBUNTU_ROOT/root/.config/pip/pip.conf"
        echo 'index-url = https://pypi.tuna.tsinghua.edu.cn/simple' >> "${'$'}UBUNTU_ROOT/root/.config/pip/pip.conf"
        echo 'index-url = "https://pypi.tuna.tsinghua.edu.cn/simple"' > "${'$'}UBUNTU_ROOT/root/.config/uv/uv.toml"

        configure_npm_defaults || return 1
      }

      configure_npm_defaults() {
        mkdir -p "${'$'}UBUNTU_ROOT/root" 2>/dev/null || true
        {
          echo 'prefix=/usr/local'
          echo 'registry=https://registry.npmmirror.com/'
        } > "${'$'}UBUNTU_ROOT/root/.npmrc"
      }

      fix_android_group_names() {
        mkdir -p "${'$'}UBUNTU_ROOT/etc" 2>/dev/null || true
        touch "${'$'}UBUNTU_ROOT/etc/group" 2>/dev/null || true
        current_groups="${'$'}(id -G 2>/dev/null || true)"
        for gid in ${'$'}current_groups; do
          case "${'$'}gid" in
            ''|*[!0-9]*) continue ;;
          esac
          if ! grep -q ":${'$'}gid:" "${'$'}UBUNTU_ROOT/etc/group" 2>/dev/null; then
            echo "android_group_${'$'}gid:x:${'$'}gid:" >> "${'$'}UBUNTU_ROOT/etc/group"
          fi
        done
      }

      LAST_PROOT_PROBE_STATUS=0
      LAST_PROOT_PROBE_OUTPUT=""

      run_proot_probe() {
        LAST_PROOT_PROBE_OUTPUT="${'$'}(
          "${'$'}BIN/proot" \
            -v 1 \
            -0 \
            --link2symlink \
            --kill-on-exit \
            -r "${'$'}UBUNTU_ROOT" \
            ${'$'}PROOT_BIND_ARGS \
            -w "${'$'}NBG_UBUNTU_ROOT_HOME" \
            /usr/bin/env -i \
              HOME=/root \
              PWD="${'$'}NBG_UBUNTU_ROOT_HOME" \
              TERM=xterm-256color \
              LANG=en_US.UTF-8 \
              PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
              /bin/bash --noprofile --norc -c 'exit 0' 2>&1
        )"
        LAST_PROOT_PROBE_STATUS="${'$'}?"
        return "${'$'}LAST_PROOT_PROBE_STATUS"
      }

      print_last_proot_probe_failure() {
        echo "PRoot startup probe failed."
        echo "exit_code=${'$'}LAST_PROOT_PROBE_STATUS"
        echo "ubuntu_root=${'$'}UBUNTU_ROOT"
        echo "proot_loader=${'$'}{PROOT_LOADER:-<unset>}"
        echo "ld_library_path=${'$'}{LD_LIBRARY_PATH:-<unset>}"
        echo "bind_args=${'$'}{PROOT_BIND_ARGS:-<none>}"
        echo "--- proot stdout/stderr begin ---"
        if [ -n "${'$'}LAST_PROOT_PROBE_OUTPUT" ]; then
          printf '%s\n' "${'$'}LAST_PROOT_PROBE_OUTPUT"
        else
          echo "<empty>"
        fi
        echo "--- proot stdout/stderr end ---"
      }

      run_in_ubuntu() {
        command_to_exec="${'$'}1"
        prepare_ubuntu_home
        prepare_shared_storage_links
        setup_proot_bind_args
        write_android_proxy_profile || return 1
        write_android_runtime_profile || return 1
        if ! run_proot_probe; then
          print_last_proot_probe_failure
          return 1
        fi
        "${'$'}BIN/proot" \
          -0 \
          --link2symlink \
          -r "${'$'}UBUNTU_ROOT" \
          ${'$'}PROOT_BIND_ARGS \
          -w "${'$'}NBG_UBUNTU_ROOT_HOME" \
          /usr/bin/env -i \
            DEBIAN_FRONTEND=noninteractive \
            HOME=/root \
            PWD="${'$'}NBG_UBUNTU_ROOT_HOME" \
            GOCACHE=/root/.cache/go-build \
            GOMODCACHE=/root/.cache/go-mod \
            GRADLE_USER_HOME=/root/.gradle \
            NPM_CONFIG_CACHE=/root/.npm \
            CARGO_HOME=/root/.cargo \
            TMPDIR=/tmp \
            TERM=xterm-256color \
            LANG=en_US.UTF-8 \
            PATH=/usr/local/node-v24/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/root/.local/bin \
            COMMAND_TO_EXEC="${'$'}command_to_exec" \
            /bin/bash -lc '. /etc/profile.d/01-nbg-android-proxy.sh 2>/dev/null || true; . /etc/profile.d/02-nbg-android-runtime.sh 2>/dev/null || true; eval "${'$'}COMMAND_TO_EXEC"'
      }

      configure_node_runtime_environment() {
        mkdir -p "${'$'}UBUNTU_ROOT/etc/profile.d" 2>/dev/null || return 1
        cat > "${'$'}UBUNTU_ROOT/etc/profile.d/00-nbg-node-path.sh" <<'EOF'
case ":${'$'}PATH:" in
  *:/usr/local/node-v24/bin:*) ;;
  *) PATH="/usr/local/node-v24/bin:${'$'}PATH" ;;
esac
export PATH
EOF
      }

      node_runtime_ready() {
        configure_node_runtime_environment || return 1
        configure_npm_defaults || return 1
        if [ ! -x "${'$'}UBUNTU_ROOT/usr/local/node-v24/bin/node" ]; then
          rm -f "${'$'}UBUNTU_ROOT/.nbg_default_tools_version" 2>/dev/null || true
          return 1
        fi
        run_in_ubuntu 'test -x /usr/local/node-v24/bin/node && test -x /usr/local/node-v24/bin/npm && node --version >/dev/null 2>&1 && npm --version >/dev/null 2>&1'
      }

      ripgrep_runtime_ready() {
        run_in_ubuntu 'command -v rg >/dev/null 2>&1 && rg --version 2>/dev/null | grep -q "ripgrep 15[.]1[.]0"'
      }

      acquire_default_tools_lock() {
        tools_lock_dir="${'$'}UBUNTU_ROOT/.nbg_default_tools.lock"
        tools_lock_pid_file="${'$'}tools_lock_dir/pid"
        tools_lock_attempt=0
        while true; do
          if mkdir "${'$'}tools_lock_dir" 2>/dev/null; then
            echo "${'$'}${'$'}" > "${'$'}tools_lock_pid_file" 2>/dev/null || true
            return 0
          fi

          if [ -f "${'$'}tools_lock_pid_file" ]; then
            tools_lock_pid="${'$'}(cat "${'$'}tools_lock_pid_file" 2>/dev/null)"
            if [ -z "${'$'}tools_lock_pid" ] || ! kill -0 "${'$'}tools_lock_pid" 2>/dev/null; then
              rm -rf "${'$'}tools_lock_dir" 2>/dev/null || true
              continue
            fi
          elif [ "${'$'}tools_lock_attempt" -gt 2 ]; then
            rm -rf "${'$'}tools_lock_dir" 2>/dev/null || true
            continue
          fi

          tools_lock_attempt="${'$'}((tools_lock_attempt + 1))"
          if [ "${'$'}tools_lock_attempt" -gt 180 ]; then
            echo "Default development tool install lock timeout" >&2
            return 1
          fi
          sleep 1
        done
      }

      release_default_tools_lock() {
        rm -rf "${'$'}UBUNTU_ROOT/.nbg_default_tools.lock" 2>/dev/null || true
      }

      install_node_from_official_tarball() {
        node_work_dir="${'$'}TMPDIR/default-node-${'$'}${'$'}"
        node_archive_name="${'$'}DEFAULT_NODE_ARCHIVE"
        node_archive="${'$'}node_work_dir/${'$'}node_archive_name"
        node_root="${'$'}UBUNTU_ROOT/usr/local/node-v24"
        node_tmp_root="${'$'}UBUNTU_ROOT/usr/local/node-v24.tmp"
        node_backup_root="${'$'}UBUNTU_ROOT/usr/local/node-v24.backup"
        node_tar_err="${'$'}node_work_dir/tar.err"

        rm -f "${'$'}UBUNTU_ROOT/.nbg_default_tools_version" 2>/dev/null || true
        rm -rf "${'$'}TMPDIR/default-node" "${'$'}TMPDIR"/default-node-* "${'$'}node_tmp_root" 2>/dev/null || true
        mkdir -p "${'$'}node_work_dir" "${'$'}UBUNTU_ROOT/usr/local/bin" 2>/dev/null || return 1

        terminal_phase node_runtime
        if [ -f "${'$'}HOME/${'$'}NBG_NODE_ARCHIVE" ]; then
          echo "Installing built-in Node.js runtime..."
          cp "${'$'}HOME/${'$'}NBG_NODE_ARCHIVE" "${'$'}node_archive" || return 1
        else
          echo "Built-in Node.js archive missing; downloading ${'$'}node_archive_name from ${'$'}DEFAULT_NODE_DIST_URL"
          if ! "${'$'}BIN/busybox" wget --no-check-certificate -O "${'$'}node_archive" "${'$'}DEFAULT_NODE_DIST_URL/${'$'}node_archive_name"; then
            echo "Failed to download Node.js tarball ${'$'}node_archive_name" >&2
            return 1
          fi
        fi

        actual_sha="${'$'}("${'$'}BIN/busybox" sha256sum "${'$'}node_archive" 2>/dev/null | "${'$'}BIN/busybox" awk '{ print ${'$'}1; exit }')"
        if [ -z "${'$'}actual_sha" ]; then
          echo "Unable to calculate Node.js tarball checksum" >&2
          return 1
        fi
        if [ "${'$'}actual_sha" != "${'$'}DEFAULT_NODE_ARCHIVE_SHA256" ]; then
          echo "Node.js tarball checksum mismatch for ${'$'}node_archive_name" >&2
          return 1
        fi

        node_tar_status=0
        if ! "${'$'}BIN/busybox" tar xf "${'$'}node_archive" -C "${'$'}node_work_dir" 2> "${'$'}node_tar_err"; then
          node_tar_status=1
          echo "Node.js tarball extraction reported errors for ${'$'}node_archive_name" >&2
          cat "${'$'}node_tar_err" >&2 2>/dev/null || true
        fi
        extracted_node_dir="${'$'}node_work_dir/${'$'}{node_archive_name%.tar.xz}"
        if [ ! -d "${'$'}extracted_node_dir" ]; then
          echo "Node.js tarball did not contain ${'$'}{node_archive_name%.tar.xz}" >&2
          return 1
        fi
        if [ "${'$'}node_tar_status" -ne 0 ] && [ ! -f "${'$'}extracted_node_dir/bin/node" ]; then
          echo "Failed to extract Node.js tarball ${'$'}node_archive_name" >&2
          return 1
        fi
        rm -f \
          "${'$'}extracted_node_dir/bin/npm" \
          "${'$'}extracted_node_dir/bin/npx" \
          "${'$'}extracted_node_dir/bin/corepack" \
          2>/dev/null || true
        ln -sf "../lib/node_modules/npm/bin/npm-cli.js" "${'$'}extracted_node_dir/bin/npm"
        ln -sf "../lib/node_modules/npm/bin/npx-cli.js" "${'$'}extracted_node_dir/bin/npx"
        ln -sf "../lib/node_modules/corepack/dist/corepack.js" "${'$'}extracted_node_dir/bin/corepack"
        if [ ! -f "${'$'}extracted_node_dir/bin/node" ]; then
          echo "Node.js tarball extraction did not create bin/node" >&2
          ls -la "${'$'}extracted_node_dir/bin" >&2 2>/dev/null || true
          return 1
        fi
        chmod 755 "${'$'}extracted_node_dir/bin/node" 2>/dev/null || true

        rm -rf "${'$'}node_tmp_root" "${'$'}node_backup_root" 2>/dev/null || true
        mv "${'$'}extracted_node_dir" "${'$'}node_tmp_root" || return 1
        if [ -d "${'$'}node_root" ]; then
          mv "${'$'}node_root" "${'$'}node_backup_root" || return 1
        fi
        if ! mv "${'$'}node_tmp_root" "${'$'}node_root"; then
          echo "Failed to install Node.js into ${'$'}node_root" >&2
          if [ -d "${'$'}node_backup_root" ] && [ ! -d "${'$'}node_root" ]; then
            mv "${'$'}node_backup_root" "${'$'}node_root" 2>/dev/null || true
          fi
          return 1
        fi

        ln -sf "../node-v24/bin/node" "${'$'}UBUNTU_ROOT/usr/local/bin/node"
        ln -sf "../node-v24/bin/npm" "${'$'}UBUNTU_ROOT/usr/local/bin/npm"
        if [ -e "${'$'}node_root/bin/npx" ]; then
          ln -sf "../node-v24/bin/npx" "${'$'}UBUNTU_ROOT/usr/local/bin/npx"
        fi
        if [ -e "${'$'}node_root/bin/corepack" ]; then
          ln -sf "../node-v24/bin/corepack" "${'$'}UBUNTU_ROOT/usr/local/bin/corepack"
        fi

        if ! configure_node_runtime_environment; then
          echo "Failed to configure Node.js PATH profile" >&2
          rm -rf "${'$'}node_root" 2>/dev/null || true
          if [ -d "${'$'}node_backup_root" ]; then
            mv "${'$'}node_backup_root" "${'$'}node_root" 2>/dev/null || true
          fi
          return 1
        fi
        if ! configure_npm_defaults; then
          echo "Failed to configure npm defaults" >&2
          rm -rf "${'$'}node_root" 2>/dev/null || true
          if [ -d "${'$'}node_backup_root" ]; then
            mv "${'$'}node_backup_root" "${'$'}node_root" 2>/dev/null || true
          fi
          return 1
        fi
        if ! node_runtime_ready; then
          echo "Node.js installation did not pass runtime verification" >&2
          rm -rf "${'$'}node_root" 2>/dev/null || true
          if [ -d "${'$'}node_backup_root" ]; then
            mv "${'$'}node_backup_root" "${'$'}node_root" 2>/dev/null || true
          fi
          return 1
        fi
        rm -rf "${'$'}node_backup_root" 2>/dev/null || true
        rm -rf "${'$'}node_work_dir" 2>/dev/null || true
      }

      install_builtin_ripgrep() {
        if ripgrep_runtime_ready; then
          return 0
        fi
        if [ ! -f "${'$'}NBG_RG_HOST_BIN" ]; then
          echo "Missing built-in ripgrep binary: ${'$'}NBG_RG_HOST_BIN" >&2
          return 1
        fi

        target="${'$'}UBUNTU_ROOT/usr/local/bin/rg"
        mkdir -p "${'$'}{target%/*}" 2>/dev/null || return 1
        cp "${'$'}NBG_RG_HOST_BIN" "${'$'}target" || return 1
        chmod 755 "${'$'}target" || return 1
        ripgrep_runtime_ready
      }

      default_development_tools_ready() {
        marker="${'$'}UBUNTU_ROOT/.nbg_default_tools_version"
        if [ ! -f "${'$'}marker" ] || [ "${'$'}(cat "${'$'}marker" 2>/dev/null)" != "${'$'}DEFAULT_TOOLS_VERSION" ]; then
          return 1
        fi
        node_runtime_ready
      }

      ensure_default_development_tools() {
        if default_development_tools_ready; then
          install_builtin_ripgrep || return 1
          return 0
        fi

        if ! acquire_default_tools_lock; then
          return 1
        fi
        if default_development_tools_ready; then
          release_default_tools_lock
          install_builtin_ripgrep || return 1
          return 0
        fi

        echo "Preparing built-in development tools..."
        if ! node_runtime_ready; then
          install_node_from_official_tarball
          status="${'$'}?"
          if [ "${'$'}status" -ne 0 ]; then
            rm -f "${'$'}UBUNTU_ROOT/.nbg_default_tools_version" 2>/dev/null || true
            echo "Default development tool installation failed" >&2
            release_default_tools_lock
            return "${'$'}status"
          fi
        fi
        if ! install_builtin_ripgrep; then
          rm -f "${'$'}UBUNTU_ROOT/.nbg_default_tools_version" 2>/dev/null || true
          release_default_tools_lock
          return 1
        fi
        echo "${'$'}DEFAULT_TOOLS_VERSION" > "${'$'}UBUNTU_ROOT/.nbg_default_tools_version"
        release_default_tools_lock
      }

      login_ubuntu() {
        command_to_exec="${'$'}1"
        if [ -z "${'$'}command_to_exec" ]; then
          command_to_exec="/bin/bash -il"
        fi
        if [ -f "${'$'}HOME/setup_fake_sysdata.sh" ]; then
          export INSTALLED_ROOTFS_DIR="${'$'}{UBUNTU_ROOT%/*}"
          export distro_name="${'$'}{UBUNTU_ROOT##*/}"
          . "${'$'}HOME/setup_fake_sysdata.sh"
          setup_fake_sysdata
        fi
        prepare_ubuntu_home
        prepare_shared_storage_links
        setup_proot_bind_args
        write_android_proxy_profile || return 1
        write_android_runtime_profile || return 1
        if ! run_proot_probe; then
          print_last_proot_probe_failure
          return 1
        fi
        exec "${'$'}BIN/proot" \
          -0 \
          --link2symlink \
          --kill-on-exit \
          -r "${'$'}UBUNTU_ROOT" \
          ${'$'}PROOT_BIND_ARGS \
          -w "${'$'}NBG_UBUNTU_ROOT_HOME" \
          /usr/bin/env -i \
            HOME=/root \
            PWD="${'$'}NBG_UBUNTU_ROOT_HOME" \
            GOCACHE=/root/.cache/go-build \
            GOMODCACHE=/root/.cache/go-mod \
            GRADLE_USER_HOME=/root/.gradle \
            NPM_CONFIG_CACHE=/root/.npm \
            CARGO_HOME=/root/.cargo \
            TMPDIR=/tmp \
            TERM=xterm-256color \
            LANG=en_US.UTF-8 \
            PATH=/usr/local/node-v24/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/root/.local/bin \
            /bin/bash -lc ". /etc/profile.d/01-nbg-android-proxy.sh 2>/dev/null || true; . /etc/profile.d/02-nbg-android-runtime.sh 2>/dev/null || true; echo NBG_TERMINAL_READY; exec ${'$'}command_to_exec"
      }

      start_shell() {
        terminal_phase ubuntu_install
        install_ubuntu || exit 1
        install_android_build_helper || exit 1
        configure_package_sources || exit 1
        fix_android_group_names || exit 1
        terminal_phase development_tools
        ensure_default_development_tools || exit 1
        terminal_phase proot_probe
        login_ubuntu
      }
    """.trimIndent()
  }
