              rm -rf "${'$'}LOCK_DIR" 2>/dev/null || true
              continue
            fi
          elif [ "${'$'}attempt" -gt 2 ]; then
            rm -rf "${'$'}LOCK_DIR" 2>/dev/null || true
            continue
          fi

          attempt="${'$'}((attempt + 1))"
          if [ "${'$'}attempt" -gt 120 ]; then
            echo "Ubuntu install lock timeout"
            return 1
          fi
